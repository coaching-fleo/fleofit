import puppeteer from 'puppeteer-core'
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new' })
const dormi = (ms) => new Promise(r => setTimeout(r, ms))
let page = await browser.newPage()
page.on('dialog', d => d.accept())
await page.setViewport({ width: 402, height: 820, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
await page.goto('http://localhost:5174/create?edit=w-completo', { waitUntil: 'domcontentloaded' })
await page.addStyleTag({ content: '.fixed.top-0.left-0.z-\\[200\\]{display:none!important} *{caret-color:transparent!important}' })
await dormi(3500)
await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.innerText.includes('Genera con IA')).click())
await dormi(1500)
const n = await page.evaluate(() => { const t = [...document.querySelectorAll('textarea')]; const el = t[t.length - 1]; el.spellcheck = false; el.focus(); return t.length })
await page.keyboard.type("Porta il For Time a 4 giri e aggiungi un EMOM da 12 minuti: 15 wall balls, 12 cal row, 10 burpees", { delay: 8 })
await dormi(800)
await page.evaluate(() => { document.activeElement.blur(); window.scrollTo(0, 0) })
await dormi(500)
await page.screenshot({ path: 'out/ia.png' })
console.log('textarea', n)
await page.close()
